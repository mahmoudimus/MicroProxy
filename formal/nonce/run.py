def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def check_forbidden_source(path):
    code = strip_comments(path.read_text())
    forbidden = [r'\{:\s*axiom', r'\{:\s*extern', r'\{:\s*verify\s+false',
                 r'\{:\s*trusted', r'\bassume\b']
    found = [pattern for pattern in forbidden if re.search(pattern, code, re.I)]
    if found:
        raise RuntimeError(f'Forbidden trusted/assumption construct in {path.name}: {found}')
    return forbidden


def load_toolchain():
    spec = importlib.util.spec_from_file_location(
        'nonce_toolchain', ROOT / 'formal/dafny/toolchain.py')
    if spec is None or spec.loader is None:
        raise RuntimeError('Cannot load the pinned Dafny toolchain verifier')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def check_verified(status, output, expected, label):
    summaries = SUMMARY.findall(output)
    if (status != 0 or len(summaries) != 1 or int(summaries[0][0]) != expected
            or int(summaries[0][1]) != 0 or BAD.search(output)):
        raise RuntimeError(f'{label}: expected {expected} verified, 0 errors; see log')
    return int(summaries[0][0])


def parse_locations(output, workspace):
    locations = []
    pattern = re.compile(r'^(.+?\.dfy)\((\d+),(\d+)\): (Error|Related location):(.*)$', re.M)
    for name, line, column, kind, message in pattern.findall(output):
        path = Path(name)
        if not path.is_absolute():
            path = workspace / path
        try:
            source_line = path.read_text().splitlines()[int(line) - 1].strip()
        except (OSError, IndexError):
            source_line = ''
        locations.append({'file': path.name, 'line': int(line), 'column': int(column),
                          'kind': kind, 'source': source_line, 'message': message.strip()})
    return locations


def check_rejected(status, output, mutant, workspace):
    summaries = SUMMARY.findall(output)
    if status != 4 or len(summaries) != 1 or int(summaries[0][1]) == 0 or BAD.search(output):
        raise RuntimeError(f'Control {mutant["name"]} did not fail a proof obligation '
                           'without timeout/resource/parse failure')
    locations = parse_locations(output, workspace)
    matches = [location for location in locations
               if location['kind'] == mutant['kind']
               and mutant['anchor'] in location['source']]
    if not matches:
        observed = [(location['kind'], location['line'], location['source'])
                    for location in locations]
        raise RuntimeError(f'Control {mutant["name"]} did not fail at the intended '
                           f'{mutant["kind"]} anchor {mutant["anchor"]!r}; observed {observed}')
    return {'status': 'proof-obligation-rejected',
            'expected': mutant['expected'],
            'anchor': mutant['anchor'],
            'observations': matches[:4],
            'summary': f'{summaries[0][0]} verified, {summaries[0][1]} errors'}


def mutations(source):
    body = '''    nonce[4] := iv[4] ^ ((pn >> 56) & 0xFF) as bv8;
    nonce[5] := iv[5] ^ ((pn >> 48) & 0xFF) as bv8;
    nonce[6] := iv[6] ^ ((pn >> 40) & 0xFF) as bv8;
    nonce[7] := iv[7] ^ ((pn >> 32) & 0xFF) as bv8;
    nonce[8] := iv[8] ^ ((pn >> 24) & 0xFF) as bv8;
    nonce[9] := iv[9] ^ ((pn >> 16) & 0xFF) as bv8;
    nonce[10] := iv[10] ^ ((pn >> 8) & 0xFF) as bv8;
    nonce[11] := iv[11] ^ (pn & 0xFF) as bv8;
'''
    if source.count(body) != 1:
        raise RuntimeError('Mutation anchor changed; review negative controls')
    wrong_endian = '''    nonce[4] := iv[4] ^ (pn & 0xFF) as bv8;
    nonce[5] := iv[5] ^ ((pn >> 8) & 0xFF) as bv8;
    nonce[6] := iv[6] ^ ((pn >> 16) & 0xFF) as bv8;
    nonce[7] := iv[7] ^ ((pn >> 24) & 0xFF) as bv8;
    nonce[8] := iv[8] ^ ((pn >> 32) & 0xFF) as bv8;
    nonce[9] := iv[9] ^ ((pn >> 40) & 0xFF) as bv8;
    nonce[10] := iv[10] ^ ((pn >> 48) & 0xFF) as bv8;
    nonce[11] := iv[11] ^ ((pn >> 56) & 0xFF) as bv8;
'''
    truncation = '''    var pn32 := pn & 0xFFFFFFFF;
    nonce[4] := iv[4] ^ ((pn32 >> 56) & 0xFF) as bv8;
    nonce[5] := iv[5] ^ ((pn32 >> 48) & 0xFF) as bv8;
    nonce[6] := iv[6] ^ ((pn32 >> 40) & 0xFF) as bv8;
    nonce[7] := iv[7] ^ ((pn32 >> 32) & 0xFF) as bv8;
    nonce[8] := iv[8] ^ ((pn32 >> 24) & 0xFF) as bv8;
    nonce[9] := iv[9] ^ ((pn32 >> 16) & 0xFF) as bv8;
    nonce[10] := iv[10] ^ ((pn32 >> 8) & 0xFF) as bv8;
    nonce[11] := iv[11] ^ (pn32 & 0xFF) as bv8;
'''
    start = source.index('  {\n    nonce := new bv8[12];')
    end = source.index('\n  }\n}', start)
    alias = source[:start] + '  {\n    nonce := iv;' + source[end:]
    preservation = source.replace('    requires iv.Length == 12\n',
                                  '    requires iv.Length == 12\n    modifies iv\n', 1)
    preservation = preservation.replace(body, body + '    iv[0] := iv[0] ^ 1 as bv8;\n', 1)
    spec_truncation = source
    for k in range(4, 8):
        shift = 8 * k
        old = f'  ghost function B{k}(pn: bv64): bv8 {{ ((pn >> {shift}) & 0xFF) as bv8 }}'
        if spec_truncation.count(old) != 1:
            raise RuntimeError(f'Spec mutation anchor changed for B{k}')
        spec_truncation = spec_truncation.replace(
            old, f'  ghost function B{k}(pn: bv64): bv8 {{ 0 as bv8 }}')
    return [
        {'name': 'wrong-endian', 'text': source.replace(body, wrong_endian, 1),
         'kind': 'Error', 'anchor': 'assert nonce[4] == NonceBytes(old(iv[..]), pn)[4];',
         'expected': 'little-endian body fails the big-endian byte-4 bridge assertion',
         'required': ['nonce[4] := iv[4] ^ (pn & 0xFF) as bv8;']},
        {'name': 'counter-truncation', 'text': source.replace(body, truncation, 1),
         'kind': 'Error', 'anchor': 'assert nonce[4] == NonceBytes(old(iv[..]), pn)[4];',
         'expected': '32-bit packet-number body fails the high-byte big-endian assertion',
         'required': ['var pn32 := pn & 0xFFFFFFFF;',
                      'nonce[4] := iv[4] ^ ((pn32 >> 56) & 0xFF) as bv8;']},
        {'name': 'alias-freshness', 'text': alias,
         'kind': 'Related location', 'anchor': 'ensures nonce != iv',
         'expected': 'returning the IV aliases the output; freshness postcondition fails',
         'required': ['nonce := iv;']},
        {'name': 'input-preservation', 'text': preservation,
         'kind': 'Related location', 'anchor': 'ensures iv[..] == old(iv[..])',
         'expected': 'mutating the caller IV fails the input-preservation postcondition',
         'required': ['modifies iv', 'iv[0] := iv[0] ^ 1 as bv8;']},
        {'name': 'counter-truncation-injectivity', 'text': spec_truncation,
         'kind': 'Related location',
         'anchor': 'ensures p == ((B7(p) as bv64) << 56)',
         'expected': 'dropping high packet-number bytes makes the decomposition/injectivity lemma fail',
         'required': ['ghost function B7(pn: bv64): bv8 { 0 as bv8 }']},
    ]


def check_aggregator(path):
    clean = re.sub(r'//[^\n]*', '', path.read_text())
    if re.sub(r'\bimport\s+[\w.*]+\s*;', '', clean).strip():
        raise RuntimeError('Unexpected executable top-level generated file')


def compare_generated(fresh, committed):
    fresh_map = snapshot(fresh, '*.java')
    committed_map = snapshot(committed, '*.java')
    missing = sorted(set(fresh_map) - set(committed_map))
    extra = sorted(set(committed_map) - set(fresh_map))
    changed = sorted(name for name in set(fresh_map) & set(committed_map)
                     if fresh_map[name] != committed_map[name])
    if missing or extra or changed:
        raise RuntimeError('Committed generated nonce sources diverge from fresh translation: '
                           f'missing={missing} extra={extra} changed={changed}')
    if not fresh_map:
        raise RuntimeError('Fresh translation produced no generated Java')
    return fresh_map, committed_map


def validate_receipt(path, source_sha, runtime_sha, version, fresh_map, aggregator_sha):
    if not path.is_file():
        raise RuntimeError('Missing checked-in GENERATED.json receipt')
    receipt = json.loads(path.read_text())
    checks = {
        'schema': receipt.get('schema') == 'microproxy.verified-nonce-generated/v1',
        'source_path': receipt.get('source', {}).get('path') == 'formal/nonce/Nonce.dfy',
        'source_sha256': receipt.get('source', {}).get('sha256') == source_sha,
        'runtime_sha256': receipt.get('runtime_sha256') == runtime_sha,
        'dafny_version': receipt.get('dafny_version') == version,
        'outer_module': receipt.get('outer_module') == OUTER_MODULE,
        'module': receipt.get('module') == MODULE,
        'output': receipt.get('output') == OUTPUT_NAME,
        'generated_java': receipt.get('generated_java') == fresh_map,
        'aggregator_sha256': receipt.get('aggregator_sha256') == aggregator_sha,
    }
    failed = [name for name, ok in checks.items() if not ok]
    if failed:
        raise RuntimeError(f'Generated receipt drifted or is stale: {failed}; review and renew')
    return receipt


def inspect_generated(fresh_pkg, java_home, classes, workspace, label):
    source_path = fresh_pkg / '__default.java'
    if not source_path.is_file():
        raise RuntimeError('Missing generated __default.java')
    source = source_path.read_text()
    if 'public static byte[] Nonce(byte[] iv, long pn)' not in source:
        raise RuntimeError('Generated Nonce signature is not raw byte[]/long')
    source_counts = {
        'Byte.valueOf': source.count('Byte.valueOf'),
        'DafnySequence': source.count('DafnySequence'),
        'select(': source.count('select('),
        'BigInteger': source.count('BigInteger'),
        'Helpers.toInt': source.count('Helpers.toInt'),
        'fillThenReturnArray': source.count('fillThenReturnArray'),
    }
    if source_counts['DafnySequence'] or source_counts['select(']:
        raise RuntimeError('Generated Nonce contains a sequence/select payload path')
    javap = java_home / 'bin/javap'
    status, output = execute(
        [javap, '-classpath', classes, '-p', '-c', '-s',
         f'{OUTER_MODULE}.{MODULE}.__default'],
        workspace / f'{label}-javap.log', timeout=120)
    if status or f'descriptor: ([BJ)[B' not in output:
        raise RuntimeError('Generated Nonce bytecode signature is not (byte[], long) -> byte[]')
    bytecode_counts = {
        'Byte.valueOf': output.count('java/lang/Byte.valueOf'),
        'DafnySequence': output.count('DafnySequence'),
        'select': output.count('select('),
        'BigInteger.valueOf': output.count('java/math/BigInteger.valueOf'),
        'Helpers.toInt': output.count('dafny/Helpers.toInt'),
        'bv64ShiftRight': output.count('dafny/Helpers.bv64ShiftRight'),
    }
    if bytecode_counts['DafnySequence'] or bytecode_counts['select']:
        raise RuntimeError('Generated bytecode contains a sequence/select payload path')
    if bytecode_counts['Byte.valueOf'] != 1:
        raise RuntimeError('Expected exactly one cached Byte.valueOf for the fresh-array zero fill, '
                           f'observed {bytecode_counts["Byte.valueOf"]}')
    return {
        'source': str(source_path),
        'source_sha256': digest(source_path),
        'signature': 'public static byte[] Nonce(byte[] iv, long pn)',
        'source_counts': source_counts,
        'bytecode_counts': bytecode_counts,
        'interpretation': (
            'The single Byte.valueOf is the cached zero used by the Dafny fresh-array '
            'initializer, not a per-payload-byte box. The twelve output bytes use primitive '
            'baload/bastore/ixor/i2b; BigInteger helper calls are constant array indices and '
            'are reported rather than hidden.'),
    }


def pipeline(args, output, locks):
    tools = validate_portable_tools(json.loads(TOOLS.read_text()))
    pins = json.loads(INPUTS.read_text())['inputs']
    required = input_inventory()
    if set(pins) != required:
        raise RuntimeError('Proof input inventory changed; review inputs.json')
    check_inputs(ROOT, pins)
    check_forbidden_source(SOURCE)
    check_forbidden_source(DOMAIN)

    args.cache = args.cache.expanduser().resolve()
    runtime = resolve_runtime(args.runtime, tools)
    workspace = Path(tempfile.mkdtemp(prefix='replay-', dir=output))
    commands = []

    def call(label, command, timeout=180):
        print(label, flush=True)
        commands.append({'step': label, 'command': [str(c) for c in command],
                         'log': str(workspace / f'{label}.log'), 'timeout': timeout})
        return execute(command, workspace / f'{label}.log', timeout=timeout)

    java_homes = [*args.java_home, *args.extra_java_home]
    jdk21, jdk25, jdk_identities = select_jdks(java_homes, workspace)
    for index, identity in enumerate(jdk_identities):
        home = Path(identity['java_home'])
        commands.append({'step': f'jdk-{index}-java-version',
                         'command': [str(home / 'bin/java'), '-version'],
                         'log': str(workspace / f'jdk-{index}-version.log'),
                         'timeout': 60})
        commands.append({'step': f'jdk-{index}-javac-version',
                         'command': [str(home / 'bin/javac'), '-version'],
                         'log': str(workspace / f'jdk-{index}-version-javac.log'),
                         'timeout': 60})

    toolchain, dafny, distribution_runtime, dafny_tools, asset, tool_identity = \
        select_toolchain(args.cache)

    code, version = call('dafny-version', [dafny, '--version'], 60)
    if code or version.strip() != tools['dafny']['version']:
        raise InputError(f'Unexpected Dafny version: {version.strip()!r}')

    for label, path in (('kernel-audit', SOURCE), ('domain-audit', DOMAIN)):
        code, audit = call(label, [dafny, 'audit', path], 180)
        if code or AUDIT_LINE not in audit or BAD.search(audit):
            raise RuntimeError(f'{label} found an unexpected trust assumption')

    kernel_source_sha = digest(SOURCE)
    if kernel_source_sha != pins[str(SOURCE.relative_to(ROOT))]:
        raise RuntimeError('Kernel source changed before verification')
    verified = check_verified(*call('kernel-proof', [dafny, 'verify', SOURCE, *FLAGS], 180),
                              EXPECTED_KERNEL_VERIFIED, 'kernel-proof')
    domain_verified = check_verified(
        *call('public-domain', [dafny, 'verify', DOMAIN, '--verify-included-files', *FLAGS], 180),
        EXPECTED_DOMAIN_VERIFIED, 'public-domain')

    controls = {}
    source_text = SOURCE.read_text()
    for mutant in mutations(source_text):
        folder = workspace / 'controls' / mutant['name']
        folder.mkdir(parents=True)
        path = folder / 'Nonce.dfy'
        path.write_text(mutant['text'])
        for required_text in mutant['required']:
            if required_text not in mutant['text']:
                raise RuntimeError(f'Control {mutant["name"]} lost its intended mutation')
        status, rejected = call('control-' + mutant['name'],
                                [dafny, 'verify', path, *FLAGS, '--error-limit', '20'], 180)
        controls[mutant['name']] = check_rejected(status, rejected, mutant, folder)
    if digest(SOURCE) != kernel_source_sha:
        raise RuntimeError('Kernel source changed during negative controls')

    # Verification and generation must use the same frozen bytes. The source
    # is re-hashed immediately before and after --no-verify translation.
    check_inputs(ROOT, pins)
    prefix = workspace / OUTPUT_NAME
    status, translated = call('generate-java', [dafny, 'translate', 'java', '--no-verify',
        '--outer-module', OUTER_MODULE, '--output', prefix, SOURCE], 180)
    if (status or 'Dafny program verifier did not attempt verification' not in translated
            or BAD.search(translated)):
        raise RuntimeError('Bounded --no-verify Java generation failed')
    if digest(SOURCE) != kernel_source_sha:
        raise RuntimeError('Kernel source changed between verification and generation')
    generated = workspace / f'{OUTPUT_NAME}-java'
    fresh_pkg = generated / GENERATED_PACKAGE
    if not (fresh_pkg / '__default.java').is_file():
        raise RuntimeError('Missing generated nonce implementation')
    aggregator = generated / f'{OUTPUT_NAME}.java'
    if not aggregator.is_file():
        raise RuntimeError('Missing generated top-level translation file')
    check_aggregator(aggregator)
    fresh_map, committed_map = compare_generated(fresh_pkg, GENERATED_SOURCE)
    aggregator_sha = digest(aggregator)
    metadata = generated / f'{OUTPUT_NAME}-java.dtr'
    validate_receipt(GENERATED_RECEIPT, kernel_source_sha, tools['runtime']['sha256'],
                     version.strip(), fresh_map, aggregator_sha)

    java_home = Path(jdk21['java_home'])
    extra_homes = [Path(jdk25['java_home'])]
    classes = workspace / 'classes'
    classes.mkdir()
    java_sources = (sorted(fresh_pkg.rglob('*.java'))
                    + [REFERENCE_SOURCE, TEST_HARNESS_SOURCE, BENCH_DRIVER])
    status, diagnostics = call('javac', [
        java_home / 'bin/javac', '--release', '21', '-g:lines,vars,source',
        '-encoding', 'UTF-8', '-Xpkginfo:always', '-Werror',
        '-Xlint:all,-serial,-cast,-rawtypes', '-cp', runtime,
        '-d', classes, *java_sources], 300)
    if status or diagnostics.strip():
        raise RuntimeError('Strict generated/harness compilation failed or warned: '
                           + diagnostics[-4000:])
    inspection = inspect_generated(fresh_pkg, java_home, classes, workspace, 'generated')
    class_hashes = snapshot(classes, '*.class')
    generated_classes = sorted((classes / GENERATED_PACKAGE).rglob('*.class'))

    java_results = []
    for index, identity in enumerate([jdk21, jdk25]):
        home = Path(identity['java_home'])
        status, tests = call(f'java-{index}-tests', [
            home / 'bin/java', '-ea', '-cp', f'{classes}{os.pathsep}{runtime}',
            'io.github.mahmoudimus.nonce.GeneratedNonceTest'], 300)
        if status or EXPECTED_TEST_LINE not in tests:
            raise RuntimeError(f'Generated nonce differential tests failed on {home}: '
                               + tests[-4000:])
        java_results.append({'java_home': str(home), 'major': identity['major'],
                             'version': identity['version'],
                             'java_sha256': identity['java_sha256'],
                             'javac_version': identity['javac_version'],
                             'javac_sha256': identity['javac_sha256'],
                             'tests': tests.strip()})

    check_inputs(ROOT, pins)
    if digest(SOURCE) != kernel_source_sha:
        raise RuntimeError('Kernel source changed during the replay')

    benchmark = None
    if not args.skip_benchmark:
        benchmark_path = output / 'benchmark.json'
        benchmark_path.unlink(missing_ok=True)
        benchmark_command = [sys.executable, BENCH_SCRIPT,
                             '--java-home', java_home, '--runtime', runtime]
        for home in extra_homes:
            benchmark_command.extend(['--extra-java-home', home])
        benchmark_command.extend([
            '--iterations', str(args.benchmark_iterations),
            '--rounds', str(args.benchmark_rounds),
            '--forks', str(args.benchmark_forks),
            '--output', benchmark_path])
        status, bench_log = call('benchmark', benchmark_command, 900)
        if status or not benchmark_path.is_file():
            raise RuntimeError('Isolated nonce benchmark failed: ' + bench_log[-4000:])
        benchmark_receipt = json.loads(benchmark_path.read_text())
        benchmark = {
            'path': str(benchmark_path),
            'sha256': digest(benchmark_path),
            'status': benchmark_receipt.get('status'),
            'jdk_runs': {key: run['summary']
                         for key, run in benchmark_receipt['jdk_runs'].items()},
            'note': 'Diagnostic only; no constant-time or JVM-timing claim.',
        }

    with __import__('zipfile').ZipFile(runtime) as jar:
        runtime_classes = len([name for name in jar.namelist() if name.endswith('.class')])
    class_hashes = snapshot(classes, '*.class')
    footprint = {
        'generated_java_files': len(fresh_map),
        'generated_java_bytes': sum(path.stat().st_size for path in fresh_pkg.rglob('*.java')),
        'generated_classes': len(generated_classes),
        'generated_class_bytes': sum(path.stat().st_size for path in generated_classes),
        'dafny_runtime_bytes': runtime.stat().st_size,
        'dafny_runtime_classes': runtime_classes,
    }
    revalidate_replay(args, tools, pins, kernel_source_sha, runtime,
                      tool_identity, jdk_identities)
    return {
        'status': 'complete',
        'scope': ('isolated VerifiedNonce byte-array primitive; the generated class is present '
                  'under quic/src/main/java and will be compiled/packaged by Maven, but this '
                  'replay does not verify PacketKey delegation or production acceptance'),
        'claims': [
            'Dafny proves the 12-byte fresh-output nonce, IV preservation, unchanged 4-byte prefix, '
            'big-endian last-8 XOR, and injectivity for all distinct 64-bit packet-number patterns under a fixed IV',
            'The universal public-domain harness has no packet-number precondition, so negative Java longs are in-domain',
            'Four required proof mutants and an extra injectivity mutant fail actual proof obligations at intended anchors',
            'Checked-in generated Java is byte-identical to fresh --no-verify translation of the same verified source',
            'Strict-generated/harness compilation and independent differential tests pass on JDK 21 and JDK 25',
            'Generated Nonce is raw byte[]/long with no sequence/select payload path and one cached Byte.valueOf initializer',
        ],
        'not_proved': [
            'cryptographic hardness or PRF security', 'JVM/CPU timing or constant-time execution',
            'side channels', 'secret erasure', 'Dafny/Boogie/Z3 correctness',
            'Dafny Java compiler/runtime correctness', 'javac/JVM correctness',
            'production JAR byte identity', 'PacketKey integration', 'Maven/CI/canonical pipeline',
        ],
        'production_note': (
            'The generated VerifiedNonce.__default class is under quic/src/main/java and WILL be '
            'compiled and packaged by Maven even while PacketKey adoption is pending. Root must '
            'inventory the actual added class and apply the adoption gates; this replay does not '
            'edit PacketKey, POM, central delivery manifests, CI or shared docs.'),
        'inputs': pins,
        'dafny_version': version.strip(),
        'dafny_executable_sha256': tool_identity['executable']['sha256'],
        'toolchain': tool_identity,
        'tool_asset': asset,
        'distribution_runtime_sha256': tool_identity['distribution_runtime']['sha256'],
        'runtime': {'path': str(runtime), 'sha256': digest(runtime)},
        'cache': str(args.cache),
        'jdk_identities': jdk_identities,
        'assumption_audit': {'kernel': AUDIT_LINE, 'domain': AUDIT_LINE},
        'forbidden_source_constructs': 'none found in code (comments stripped)',
        'source_sha256': {'before': kernel_source_sha, 'after': digest(SOURCE)},
        'verified': verified,
        'public_domain_verified': domain_verified,
        'controls': controls,
        'generated_java': fresh_map,
        'delivered_generated_java': committed_map,
        'top_level_aggregator_sha256': aggregator_sha,
        'translation_metadata_sha256': digest(metadata) if metadata.is_file() else None,
        'generated_receipt_sha256': digest(GENERATED_RECEIPT),
        'inspection': inspection,
        'classes': class_hashes,
        'footprint': footprint,
        'javac': {'java_home': str(java_home),
                  'javac_sha256': jdk21['javac_sha256'],
                  'version': jdk21['javac_version']},
        'java_runs': java_results,
        'benchmark': benchmark,
        'commands': commands,
        'workspace': str(workspace),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=default_output())
    parser.add_argument('--cache', type=Path, default=default_cache())
    parser.add_argument('--runtime', type=Path, default=default_runtime(),
                        help='explicit pinned DafnyRuntime-4.9.1.jar')
    parser.add_argument('--java-home', type=Path, action='append', default=[],
                        help='explicit JDK home; repeat with one JDK 21 and one JDK 25')
    parser.add_argument('--extra-java-home', type=Path, action='append', default=[],
                        help='legacy alias for an additional explicit JDK home')
    parser.add_argument('--skip-benchmark', action='store_true')
    parser.add_argument('--benchmark-iterations', type=int, default=200_000)
    parser.add_argument('--benchmark-rounds', type=int, default=5)
    parser.add_argument('--benchmark-forks', type=int, default=5)
    args = parser.parse_args(argv)
    output = args.output.expanduser().resolve()
    output.mkdir(parents=True, exist_ok=True)
    with (output / '.lock').open('w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        report = output / 'report.json'
        report.unlink(missing_ok=True)
        atomic_report(report, {'status': 'incomplete'})
        previous = signal.getsignal(signal.SIGTERM)

        def cancel(signum, frame):
            raise KeyboardInterrupt('Proof replay terminated')

        signal.signal(signal.SIGTERM, cancel)
        try:
            try:
                result = pipeline(args, output, lock)
            except Exception as error:
                atomic_report(report, {'status': 'failed', 'error': str(error)})
                print(str(error), file=sys.stderr)
                return 1
            atomic_report(report, result)
            print(f'Complete: {report}', flush=True)
        finally:
            signal.signal(signal.SIGTERM, previous)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
