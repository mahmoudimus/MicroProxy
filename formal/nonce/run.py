VERSION_PATTERN = re.compile(r'version\s+"(\d+)(?:[._]\d+)*"')
JAVAC_PATTERN = re.compile(r'javac\s+(\d+)(?:[._]\d+)*')


def probe_jdk(home, log):
    home = Path(home).expanduser().resolve()
    if not home.is_dir():
        raise InputError(f'Missing JDK home: {home}')
    java = home / 'bin/java'
    javac = home / 'bin/javac'
    if not java.is_file() or not javac.is_file():
        raise InputError(f'JDK home must contain bin/java and bin/javac: {home}')
    status, output = execute([java, '-version'], log, 60)
    if status:
        raise InputError(f'JDK runtime unavailable: {home}')
    match = VERSION_PATTERN.search(output)
    if not match:
        raise InputError(f'Cannot identify JDK runtime version: {home}')
    major = int(match.group(1))
    status, javac_output = execute([javac, '-version'],
                                   log.with_name(log.stem + '-javac.log'), 60)
    if status:
        raise InputError(f'JDK compiler unavailable: {home}')
    javac_match = JAVAC_PATTERN.search(javac_output)
    if not javac_match or int(javac_match.group(1)) != major:
        raise InputError(f'JDK java/javac major versions disagree: {home}')
    return {
        'java_home': str(home),
        'major': major,
        'version': output.strip(),
        'javac_version': javac_output.strip(),
        'java_sha256': digest(java),
        'javac_sha256': digest(javac),
    }


def select_jdks(homes, workspace):
    if not homes:
        raise InputError('Pass one explicit JDK 21 and one explicit JDK 25 with --java-home')
    resolved = []
    for raw in homes:
        home = Path(raw).expanduser().resolve()
        if home in resolved:
            raise InputError(f'Duplicate JDK home: {home}')
        resolved.append(home)
    identities = [probe_jdk(home, Path(workspace) / f'jdk-{index}-version.log')
                  for index, home in enumerate(resolved)]
    by_major = {}
    for identity in identities:
        by_major.setdefault(identity['major'], []).append(identity)
    if (len(identities) != 2 or len(by_major.get(21, [])) != 1
            or len(by_major.get(25, [])) != 1):
        observed = ', '.join(f'{item["major"]} ({item["java_home"]})'
                             for item in identities)
        raise InputError('Require exactly one JDK 21 canonical compiler and one JDK 25 '
                         f'runtime; observed {observed}')
    return by_major[21][0], by_major[25][0], identities


def revalidate_replay(args, tools, pins, kernel_source_sha, runtime, identity, jdk_identities):
    check_inputs(ROOT, pins)
    if digest(SOURCE) != kernel_source_sha:
        raise InputError('Kernel source changed during the replay')
    require_digest(runtime, tools['runtime']['sha256'], 'Maven Dafny runtime')
    toolchain = load_toolchain()
    dafny, distribution_runtime, manifest, asset = toolchain.install(args.cache)
    current = distribution_identity(args.cache, asset, dafny, distribution_runtime, manifest)
    current['asset_key'] = identity['asset_key']
    if current != identity:
        raise InputError('The validated Dafny toolchain changed during the replay')
    for item in jdk_identities:
        home = Path(item['java_home'])
        require_digest(home / 'bin/java', item['java_sha256'],
                       f'JDK {item["major"]} java')
        require_digest(home / 'bin/javac', item['javac_sha256'],
                       f'JDK {item["major"]} javac')


