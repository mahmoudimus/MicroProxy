def digest(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def snapshot(root, pattern):
    return {str(path.relative_to(root)): digest(path)
            for path in sorted(Path(root).rglob(pattern)) if path.is_file()}


def atomic_report(path, report):
    temporary = path.with_suffix('.tmp')
    temporary.write_text(json.dumps(report, indent=2) + '\n')
    temporary.replace(path)


def live_group(group):
    states = subprocess.check_output(['ps', '-axo', 'pgid=,stat='], text=True, timeout=2)
    return any(int(parts[0]) == group and not parts[1].startswith('Z')
               for line in states.splitlines() if len(parts := line.split()) == 2)


def signal_group(group, sig):
    try:
        os.killpg(group, sig)
    except PermissionError:
        if live_group(group):
            raise


def stop_group(process):
    quiescent = False
    try:
        signal_group(process.pid, signal.SIGTERM)
        deadline = time.monotonic() + 0.5
        while time.monotonic() < deadline:
            try:
                quiescent = not live_group(process.pid)
            except (OSError, subprocess.SubprocessError):
                break
            if quiescent:
                break
            time.sleep(0.02)
    except ProcessLookupError:
        quiescent = True
    finally:
        try:
            if not quiescent:
                signal_group(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        finally:
            process.wait(timeout=1)


def execute(command, log, timeout=180):
    with log.open('w') as stream:
        process = None
        completed = False
        pending = []
        handlers = {s: signal.getsignal(s) for s in (signal.SIGTERM, signal.SIGINT)}
        try:
            for s in handlers:
                signal.signal(s, lambda signum, frame: pending.append(signum))
            try:
                process = subprocess.Popen([str(c) for c in command], cwd=ROOT,
                                           stdout=stream, stderr=subprocess.STDOUT,
                                           start_new_session=True)
            finally:
                for s, handler in handlers.items():
                    signal.signal(s, handler)
            if pending:
                raise KeyboardInterrupt('Cancelled while starting tool')
            status = process.wait(timeout=timeout)
            completed = True
        except subprocess.TimeoutExpired:
            status = 124
            stream.write('\nRunner timeout; terminating process group.\n')
        finally:
            if process is not None and not completed:
                stop_group(process)
    return status, log.read_text(errors='replace')


def check_inputs(root, pins):
    for name, expected in pins.items():
        path = root / name
        if not path.is_file() or digest(path) != expected:
            raise RuntimeError(f'Input changed; review before renewing pin: {name}')
    return dict(pins)


def require_digest(path, expected, label):
    path = Path(path)
    if not path.is_file():
        raise InputError(f'{label} is missing: {path}')
    actual = digest(path)
    if actual != expected:
        raise InputError(f'{label} checksum mismatch: expected {expected}, observed {actual}')
    return actual


