"""Trusted compiler adaptation for exactly two verified bounded-shift methods.

Dafny permits shifts by64; the JVM masks counts. PacketKernel.ShiftLeft/Right
require count<64 and prove equivalence to masked counts. No other runtime call
or packaging transformation is accepted. This pass is part of compiler trust.
"""
import re


def lower(source):
    replacements = []
    for name, operator in (('ShiftRight', '>>>'), ('ShiftLeft', '<<')):
        token = 'dafny.Helpers.bv64' + name + '('
        if source.count(token) != 1:
            raise RuntimeError('Expected exactly one bounded ' + name + ' intrinsic')
        start = source.index(token)
        declarations = list(re.finditer(r'public static long (\w+)\s*\(', source[:start]))
        if not declarations or declarations[-1].group(1) != name:
            raise RuntimeError('Shift intrinsic outside its verified helper')
        cursor = start + len(token)
        depth, comma = 1, None
        while cursor < len(source) and depth:
            char = source[cursor]
            if char == '(':
                depth += 1
            elif char == ')':
                depth -= 1
            elif char == ',' and depth == 1:
                if comma is not None:
                    raise RuntimeError('Unexpected intrinsic arity')
                comma = cursor
            cursor += 1
        if depth or comma is None:
            raise RuntimeError('Malformed bounded shift intrinsic')
        a = source[start + len(token):comma].strip()
        b = source[comma + 1:cursor - 1].strip()
        if (re.sub(r'\s+', '', a) != 'value'
                or re.sub(r'\s+', '', b) not in ('((byte)count)', '((byte)(count))')):
            raise RuntimeError('Bounded helper argument shape changed; review compiler output')
        replacements.append((start, cursor, f'({a} {operator} {b})'))
    for start, end, replacement in sorted(replacements, reverse=True):
        source = source[:start] + replacement + source[end:]
    if source.count('import PacketSpec.*;') != 1:
        raise RuntimeError('Expected one unused proof-module import')
    source = source.replace('import PacketSpec.*;', '')
    if 'PacketSpec' in source or 'dafny.' in source or 'java.math.' in source:
        raise RuntimeError('Unexpected generated runtime/spec dependency')
    return ('// Generated by pinned Dafny plus the reviewed bounded-shift lowering pass. DO NOT EDIT.\n' + source)
