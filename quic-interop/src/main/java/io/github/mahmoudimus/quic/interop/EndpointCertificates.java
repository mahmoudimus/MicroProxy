package io.github.mahmoudimus.quic.interop;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyFactory;
import java.security.KeyStore;
import java.security.PrivateKey;
import java.security.cert.CertificateFactory;
import java.security.cert.X509Certificate;
import java.security.spec.PKCS8EncodedKeySpec;
import java.util.ArrayList;
import java.util.Base64;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import javax.net.ssl.TrustManagerFactory;
import javax.net.ssl.X509TrustManager;

/** JCA PEM loader, including the SEC1 named-curve EC keys generated by certs.sh. */
final class EndpointCertificates {
    private static final Pattern PEM = Pattern.compile("-----BEGIN ([A-Z0-9 ]+)-----\\s*([A-Za-z0-9+/=\\s]+?)-----END \\1-----");
    private EndpointCertificates() {}

    static List<X509Certificate> chain(Path path) throws Exception {
        try (var in = Files.newInputStream(path)) {
            var certificates = CertificateFactory.getInstance("X.509").generateCertificates(in);
            List<X509Certificate> result = new ArrayList<>();
            for (var cert : certificates) result.add((X509Certificate) cert);
            if (result.isEmpty()) throw new IOException("empty certificate chain: " + path);
            return List.copyOf(result);
        }
    }

    static PrivateKey key(Path path) throws Exception {
        String text = Files.readString(path, StandardCharsets.US_ASCII);
        byte[] pkcs8 = null;
        byte[] sec1 = null;
        byte[] parameters = null;
        Matcher matcher = PEM.matcher(text);
        while (matcher.find()) {
            byte[] der = Base64.getMimeDecoder().decode(matcher.group(2));
            switch (matcher.group(1)) {
                case "PRIVATE KEY" -> pkcs8 = der;
                case "EC PRIVATE KEY" -> sec1 = der;
                case "EC PARAMETERS" -> parameters = der;
                default -> {}
            }
        }
        if (pkcs8 == null && sec1 != null) {
            // RFC 5915 ECPrivateKey [0] parameters holds a named-curve OBJECT IDENTIFIER.
            if (parameters == null) parameters = curveParameters(sec1);
            if (parameters == null || parameters[0] != 0x06) throw new IOException("SEC1 key has no named-curve parameters");
            byte[] algorithm = der(0x30, concat(new byte[] {6, 7, 0x2a, (byte) 0x86, 0x48, (byte) 0xce, 0x3d, 2, 1}, parameters));
            pkcs8 = der(0x30, concat(new byte[] {2, 1, 0}, algorithm, der(4, sec1)));
        }
        if (pkcs8 == null) throw new IOException("expected unencrypted PKCS#8 or SEC1 EC private key: " + path);
        for (String algorithm : List.of("EC", "RSA", "Ed25519", "Ed448")) {
            try {
                return KeyFactory.getInstance(algorithm).generatePrivate(new PKCS8EncodedKeySpec(pkcs8));
            } catch (java.security.GeneralSecurityException ignored) {
                // Try the next supported key algorithm; the final error identifies the input.
            }
        }
        throw new IOException("unsupported or invalid private key: " + path);
    }

    private static byte[] curveParameters(byte[] sec1) throws IOException {
        int[] at = {0};
        if (sec1[at[0]++] != 0x30) throw new IOException("invalid SEC1 sequence");
        length(sec1, at);
        while (at[0] < sec1.length) {
            int tag = sec1[at[0]++] & 0xff;
            int size = length(sec1, at);
            int end = Math.addExact(at[0], size);
            if (end > sec1.length) throw new IOException("truncated SEC1 key");
            if (tag == 0xa0) return java.util.Arrays.copyOfRange(sec1, at[0], end);
            at[0] = end;
        }
        return null;
    }

    private static int length(byte[] bytes, int[] at) throws IOException {
        if (at[0] >= bytes.length) throw new IOException("truncated DER length");
        int length = bytes[at[0]++] & 0xff;
        if (length < 128) return length;
        int count = length & 0x7f;
        if (count == 0 || count > 4 || at[0] + count > bytes.length) throw new IOException("invalid DER length");
        length = 0;
        for (int i = 0; i < count; i++) length = Math.addExact(Math.multiplyExact(length, 256), bytes[at[0]++] & 0xff);
        return length;
    }

    private static byte[] concat(byte[]... arrays) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        for (byte[] array : arrays) out.writeBytes(array);
        return out.toByteArray();
    }

    private static byte[] der(int tag, byte[] content) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        out.write(tag);
        if (content.length < 128) out.write(content.length);
        else {
            int count = (32 - Integer.numberOfLeadingZeros(content.length) + 7) / 8;
            out.write(0x80 | count);
            for (int shift = (count - 1) * 8; shift >= 0; shift -= 8) out.write(content.length >>> shift);
        }
        out.writeBytes(content);
        return out.toByteArray();
    }

    static X509TrustManager trust(Path ca) throws Exception {
        KeyStore store = KeyStore.getInstance(KeyStore.getDefaultType());
        store.load(null, null);
        List<X509Certificate> chain = chain(ca);
        for (int i = 0; i < chain.size(); i++) store.setCertificateEntry("interop-ca-" + i, chain.get(i));
        TrustManagerFactory factory = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
        factory.init(store);
        for (var manager : factory.getTrustManagers()) if (manager instanceof X509TrustManager x509) return x509;
        throw new IOException("no X.509 trust manager available");
    }
}
